import {test,expect} from "@playwright/test";

test.beforeEach(async({page})=>{
 await page.clock.setFixedTime(new Date("2026-11-11T00:00:00Z"));
 await page.goto("/");
 await page.getByLabel("Driver name",{exact:true}).fill("Safety UI Driver");
 await page.getByLabel("Licence number",{exact:true}).fill("TEST");
 await page.getByLabel("Driver base",{exact:true}).selectOption("QLD");
 await page.getByRole("button",{name:"Save driver settings",exact:true}).click();
});
test("past-day Work/Rest blocks cannot change without a 15-minute edit confirmation",async({page})=>{
 const date=page.getByLabel("Diary date",{exact:true});
 await date.fill("2026-11-10");await date.press("Tab");
 const cell=page.locator('.swipe-block[data-slot="0"]');
 await expect(cell).toBeDisabled();
 await expect(cell).toHaveAttribute("aria-pressed","false");
 await expect(page.getByText("Past page locked")).toBeVisible();
 await page.getByRole("button",{name:"Unlock to edit"}).click();
 await expect(page.getByRole("dialog")).toContainText("15 minutes");
 await page.getByRole("button",{name:"Cancel",exact:true}).click();
 await expect(cell).toBeDisabled();
 await page.getByRole("button",{name:"Unlock to edit"}).click();
 await page.getByRole("button",{name:"Unlock for 15 minutes"}).click();
 await expect(cell).toBeEnabled();
 await cell.click();
 await expect(cell).toHaveAttribute("aria-pressed","true");
 await page.getByRole("button",{name:"Lock now"}).click();
 await expect(cell).toBeDisabled();
 await page.reload();
 await date.fill("2026-11-10");await date.press("Tab");
 await expect(cell).toBeDisabled();
 await expect(cell).toHaveAttribute("aria-pressed","true");
});
test("date and numbered-page navigation remain reachable without accidental edits",async({page})=>{
 const date=page.getByLabel("Diary date",{exact:true});
 await date.fill("2026-11-10");await date.press("Tab");
 await expect(date).toHaveValue("2026-11-10");
 await page.getByRole("button",{name:"Previous diary day"}).click();
 await expect(date).toHaveValue("2026-11-09");
 await page.getByRole("button",{name:"Next diary day"}).click();
 await expect(date).toHaveValue("2026-11-10");
 await page.getByRole("button",{name:"Jump to page"}).click();
 await expect(page.getByLabel("Scroll to page number")).toBeVisible();
 await expect(page.getByLabel("Scroll to page number").locator('option[value="000"]')).toHaveCount(0);
 await expect(page.getByLabel("Scroll to page number").locator('option[value="0"]')).toHaveText("000");
 await expect(page.getByLabel("Scroll to page number").locator('option[value="100"]')).toHaveText("100");
 await page.getByRole("button",{name:"Close dialog"}).click();
 await expect(page.locator(".swipe-block[data-slot='0']")).toBeDisabled();
});
test("save a major route estimate and review a read-only return-trip forecast",async({page})=>{
 await page.getByText("Plan major trip",{exact:true}).click();
 await page.getByLabel("Trip name",{exact:true}).fill("Melbourne – Brisbane");
 await page.getByLabel("Work hours (one way)",{exact:true}).fill("20");
 await page.getByLabel("Rest hours (one way)",{exact:true}).fill("12");
 await page.getByRole("button",{name:"Save trip estimate"}).click();
 await expect(page.getByLabel("Saved trip")).not.toHaveValue("");
 await page.getByRole("button",{name:"Return trip",exact:true}).click();
 await expect(page.locator(".major-trip-estimates")).toContainText("40h 00m");
 await expect(page.locator(".major-trip-estimates")).toContainText("24h 00m");
 const before=await page.getByLabel("Page totals").textContent();
 await page.getByRole("button",{name:"Check trip availability"}).click();
 await expect(page.locator(".major-trip-result")).toBeVisible();
 await expect(page.locator(".major-trip-result")).toContainText(/Needs review|Estimate insufficient|Possible — verify/);
 await expect(page.getByLabel("Page totals")).toHaveText(before!);
 await page.reload();
 await page.getByText("Plan major trip",{exact:true}).click();
 await page.getByLabel("Saved trip").selectOption({label:"Melbourne – Brisbane"});
 await expect(page.getByLabel("Work hours (one way)")).toHaveValue("20");
 await expect(page.getByLabel("Rest hours (one way)")).toHaveValue("12");
});
